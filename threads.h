#ifndef THREADS_H
#define THREADS_H

#include "ntpd.h"

/* ============================================================================
 * start_peer_thread - Запуск потока обработки NTP-пэера
 *
 * Согласно RFC 5905 Section 5, каждый NTP-пэр обрабатывается в отдельном
 * потоке. Поток обрабатывает входящие запросы и отправляет ответы.
 *
 * @param sock_fd Файловый дескриптор сокетa (должен быть открыт и связан)
 * @param ip IP-адрес пэера (строка, например "192.168.1.1")
 * @param port Порт пэера (строка, например "123")
 * @param peer_state Указатель на структуру PeerState (может быть NULL)
 * @param idx Индекс в пуле пэеров (0 .. MAX_PEERS-1)
 *
 * @return 0 на успех, < 0 на ошибку
 *
 * @note Функция создаёт и запускает поток в фоновом режиме.
 * @note Поток автоматически очищает ресурсы при завершении.
 * ============================================================================
 */
int start_peer_thread(int sock_fd, const char* ip, const char* port, PeerState* peer_state, int idx);

/* ============================================================================
 * stop_peer_thread - Остановка потока обработки пэера
 *
 * @note Функция gracefully останавливает поток, ожидая его завершения.
 * ============================================================================
 */
void stop_peer_thread(void);

/* ============================================================================
 * start_clock_thread - Запуск потока обработки системных часов
 *
 * Поток обрабатывает коррекцию системных часов (дисплей, календарь) согласно
 * RFC 5905 Section 5.2.
 *
 * @param interval_sec Интервал обновления в секундах (по умолчанию 64)
 *
 * @return 0 на успех, < 0 на ошибку
 *
 * @note Поток пробуждается каждые interval_sec для проверки коррекции часов.
 * @note Функция создаёт и запускает поток в фоновом режиме.
 * @note Поток автоматически очищает ресурсы при завершении.
 * ============================================================================
 */
int start_clock_thread(int interval_sec);

/* ============================================================================
 * stop_clock_thread - Остановка потока обработки часов
 *
 * @note Функция gracefully останавливает поток, ожидая его завершения.
 * ============================================================================
 */
void stop_clock_thread(void);

/* ============================================================================
 * clock_thread_notify - Уведомление потока часов об изменении
 *
 * @return 0 на успех, < 0 на ошибку
 *
 * @note Используется для немедленного пробуждения потока часов.
 * ============================================================================
 */
int clock_thread_notify(void);

/* ============================================================================
 * clock_thread_get_last_offset - Получение последнего значения коррекции
 *
 * @return Последнее значение коррекции в микросекундах
 *
 * @note Функция синхронизируется с потоком часов.
 * ============================================================================
 */
int64_t clock_thread_get_last_offset(void);

/* ============================================================================
 * clock_thread_get_last_correction - Получение последней коррекции
 *
 * @return Последняя коррекция: SLEW или STEP
 *
 * @note SLEW - плавная коррекция, STEP - мгновенная коррекция.
 * ============================================================================
 */
int clock_thread_get_last_correction(void);

/* ============================================================================
 * cleanup_peer_thread - Очистка ресурсов потока пэера
 *
 * Вызывается при завершении работы программы.
 * ============================================================================
 */
void cleanup_peer_thread(void);

/* ============================================================================
 * cleanup_clock_thread - Очистка ресурсов потока часов
 *
 * Вызывается при завершении работы программы.
 * ============================================================================
 */
void cleanup_clock_thread(void);

#endif /* THREADS_H */
